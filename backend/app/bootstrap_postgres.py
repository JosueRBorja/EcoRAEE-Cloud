"""Initialize an empty PostgreSQL database from generated demonstration data."""
import os
import re
import secrets
import sqlite3
import tempfile
from contextlib import closing
from pathlib import Path

from . import base_datos
from .principal import initialize_demo_data
from .seguridad import hash_password


def translate(sql):
    sql = re.sub(r'\bTEXT(.*?) COLLATE NOCASE', r'CITEXT\1', sql, flags=re.I)
    sql = sql.replace(' INTEGER PRIMARY KEY AUTOINCREMENT', ' INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    sql = re.sub(r"typeof\(\w+\)='integer' AND ", '', sql)
    sql = sql.replace("strftime('%Y-%m-%dT%H:%M:%fZ','now')",
                      """to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')""")
    return sql


def migrate_demo(source, target):
    source.row_factory = sqlite3.Row
    objects = source.execute("SELECT type,name,tbl_name,sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid").fetchall()
    tables = [obj for obj in objects if obj['type'] == 'table']
    target.execute('CREATE EXTENSION IF NOT EXISTS citext')
    for table in tables:
        sql = re.sub(r',\s*FOREIGN KEY\([^)]+\) REFERENCES \w+\([^)]+\)', '', table['sql'], flags=re.I)
        sql = re.sub(r' REFERENCES \w+\([^)]+\)(?: ON DELETE \w+)?', '', sql, flags=re.I)
        target.execute(translate(sql))
    for table in tables:
        name = table['name']
        columns = source.execute(f'PRAGMA table_info("{name}")').fetchall()
        fields = ','.join(f'"{col["name"]}"' for col in columns)
        values = ','.join(['%s'] * len(columns))
        with target.cursor() as cursor:
            cursor.executemany(f'INSERT INTO "{name}" ({fields}) VALUES ({values})',
                               [tuple(row) for row in source.execute(f'SELECT * FROM "{name}"')])
        if 'AUTOINCREMENT' in table['sql']:
            target.execute(f"""SELECT setval(pg_get_serial_sequence(%s, 'id'),
                coalesce(max(id),1), count(*)>0) FROM "{name}" """, (name,))
    for table in tables:
        name = table['name']
        keys = {}
        for key in source.execute(f'PRAGMA foreign_key_list("{name}")'):
            keys.setdefault(key['id'], []).append(key)
        for columns in keys.values():
            local = ','.join(f'"{key["from"]}"' for key in columns)
            remote = ','.join(f'"{key["to"]}"' for key in columns)
            ref = columns[0]['table']
            deletion = columns[0]['on_delete']
            target.execute(f'ALTER TABLE "{name}" ADD FOREIGN KEY ({local}) REFERENCES "{ref}" ({remote}) ON DELETE {deletion}')
    for obj in objects:
        sql = obj['sql']
        if obj['type'] == 'index':
            target.execute(sql.replace('sku COLLATE NOCASE', 'lower(sku)'))
        if obj['type'] == 'view':
            sql = sql.replace('VIEW IF NOT EXISTS', 'VIEW')
            sql = re.sub(r"sum\((c.classification(?:='[^']+'| IN \([^)]*\)))\)", r'sum((\1)::int)', sql)
            target.execute(sql)
        if obj['type'] == 'trigger':
            header, body = sql.split('BEGIN SELECT RAISE(ABORT, ', 1)
            declaration, condition = header.split('WHEN', 1)
            name = obj['name']
            condition = re.sub(r"typeof\(NEW.\w+\)!='integer' OR ", '', condition)
            message = body.split(');', 1)[0]
            target.execute(f"""CREATE FUNCTION {name}_fn() RETURNS trigger LANGUAGE plpgsql AS $$
                BEGIN IF {condition} THEN RAISE EXCEPTION USING ERRCODE='23514', MESSAGE={message};
                END IF; RETURN NEW; END;
                $$""")
            declaration = declaration.replace('TRIGGER IF NOT EXISTS', 'TRIGGER')
            target.execute(f'{declaration} FOR EACH ROW EXECUTE FUNCTION {name}_fn()')


def main():
    import psycopg

    dsn = os.environ.pop('ECORAEE_POSTGRES_DSN')
    with psycopg.connect(dsn) as target:
        target.execute('SELECT pg_advisory_xact_lock(224651)')
        if target.execute("SELECT to_regclass('public.schema_migrations')").fetchone()[0]:
            return
        with tempfile.TemporaryDirectory() as folder:
            base_datos.DB_PATH = Path(folder) / 'demo.db'
            initialize_demo_data()
            with closing(sqlite3.connect(base_datos.DB_PATH)) as source:
                for user_id, role in source.execute('SELECT id,role FROM users').fetchall():
                    password = os.getenv(f'ECORAEE_DEMO_{role.upper()}_PASSWORD') or secrets.token_urlsafe(32)
                    source.execute('UPDATE users SET password_hash=? WHERE id=?', (hash_password(password), user_id))
                migrate_demo(source, target)


if __name__ == '__main__':
    main()
